/** Split outer ORs only, preserving SQL quoted strings, nested CASE expressions and coalesce validators. */
export function outerSqlBranches(value: string): string[] {
  const text = value.trim(), outside: number[] = [];
  let depth = 0, quoted = false;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === "'") {
      if (quoted && text[i + 1] === "'") { i++; continue; }
      quoted = !quoted;
    }
    if (quoted) continue;
    if (text[i] === "(") depth++;
    if (text[i] === ")") depth--;
    if (depth === 0) outside.push(i);
  }
  if (depth !== 0 || quoted) throw new Error("unbalanced_cli_predicate");
  if (text.startsWith("(") && text.endsWith(")") && outside.every(i => i === text.length - 1)) return outerSqlBranches(text.slice(1, -1));
  const splits = outside.filter(i => text.slice(i, i + 4) === " OR ");
  if (!splits.length) return [text];
  const parts: string[] = [];
  let start = 0;
  for (const split of splits) { parts.push(...outerSqlBranches(text.slice(start, split))); start = split + 4; }
  return [...parts, ...outerSqlBranches(text.slice(start))];
}

const targets = [
  { table: "model_capacity_requests", name: "model_capacity_requests_logical_check", symbol: "opencodeCliLogicalSql", expected: 2,
    guard: "provider='opencode-cli' AND class IN ('first','second') AND pool='reviewer' AND route_id IN ('crawl-agent-review','second-review')" },
  { table: "model_capacity_requests", name: "model_capacity_requests_dispatch_check", symbol: "opencodeCliDispatchSql", expected: 1,
    guard: "provider='opencode-cli' AND dispatch_binding->>'kind' IN ('ai1_legacy_cli','ai1_item_cli','ai2_item_cli')" },
  { table: "model_capacity_events", name: "model_capacity_events_terminal_check", symbol: "opencodeCliEventTerminalSql", expected: 1,
    guard: "evidence->'dispatch'->'binding'->>'provider'='opencode-cli' AND evidence->'dispatch'->'binding'->>'kind' IN ('ai1_legacy_cli','ai1_item_cli','ai2_item_cli')" },
] as const;

const generated = targets.map(target => {
  const statement = baseline.split("--> statement-breakpoint").find(sql => sql.includes(`ADD CONSTRAINT ${target.name} CHECK`));
  const predicate = statement && /CHECK \(([\s\S]*)\);\s*$/.exec(statement)?.[1];
  if (!predicate) throw new Error(`missing_cli_baseline:${target.name}`);
  const branches = outerSqlBranches(predicate).filter(branch => branch.includes("('claude-cli','grok-cli')"));
  if (branches.length !== target.expected) throw new Error(`unexpected_cli_branch_count:${target.name}`);
  const added = branches.map(branch => branch.replaceAll("('claude-cli','grok-cli')", "('opencode-cli')")
    .replaceAll("('claude-cli','grok-cli','codex-cli')", "('opencode-cli')"));
  const sql = `coalesce((${target.guard}) AND (${added.map(branch => `(${branch})`).join(" OR ")}),false)`;
  if (sql.includes("$branch$") || sql.includes("$guard$")) throw new Error("cli_predicate_tag_collision");
  return { ...target, sql };
});

